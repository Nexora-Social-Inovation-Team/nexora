/* global fetch, console, URL */
/**
 * Regenerates dictionary.generated.js from the UT1 (Universite Toulouse 1
 * Capitole) blacklists, mirrored as plain text so this needs no tar or gzip.
 *
 * Run: npm run dict:build --workspace nexora-extension
 *
 * Only the UT1 categories that map cleanly onto a NEXORA CategoryId are pulled.
 * `games` (34k), `jobsearch` (61k) and `shopping` (37k) are deliberately left
 * out: they would triple the bundle for hosts a teenager rarely sits on, and
 * the few that matter (roblox, steam) are hand rows in dictionary.js.
 *
 * UT1 has adult/gambling/malware lists. None of them are mapped and none ever
 * should be: harmful minutes come from the seed, never from a live blocklist
 * (docs/building-blocks/07-extension.md).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const BASE = "https://raw.githubusercontent.com/olbat/ut1-blacklists/master/blacklists";

/** UT1 category -> NEXORA CategoryId. `harmful` is not a legal target here. */
const SOURCES = {
  sports: "sports",
  social_networks: "entertainment",
  "audio-video": "entertainment",
  manga: "entertainment",
  celebrity: "entertainment",
  chat: "entertainment",
  liste_bu: "science",
  financial: "entrepreneurship",
};

/** arts, culture and national_memory have no UT1 equivalent; they stay hand-written. */
const out = new Map();

for (const [source, category] of Object.entries(SOURCES)) {
  if (category === "harmful") throw new Error(`refusing to map ${source} to harmful`);
  const res = await fetch(`${BASE}/${source}/domains`);
  if (!res.ok) throw new Error(`${source}: HTTP ${res.status}`);
  let kept = 0;
  for (const line of (await res.text()).split("\n")) {
    const host = line.trim().toLowerCase();
    // Skip comments, bare TLDs and anything with a path, port or wildcard.
    if (!host || host.startsWith("#") || !/^[a-z0-9.-]+\.[a-z]{2,}$/.test(host)) continue;
    if (out.has(host)) continue;
    out.set(host, category);
    kept++;
  }
  console.log(`${source.padEnd(16)} -> ${category.padEnd(16)} ${kept}`);
}

const rows = [...out].sort(([a], [b]) => (a < b ? -1 : 1));
const body = rows.map(([host, category]) => `"${host}":"${category}"`).join(",\n");
const file = `/**
 * GENERATED by scripts/build-dictionary.mjs - do not edit by hand.
 *
 * Source: UT1 Capitole blacklists (https://dsi.ut-capitole.fr/blacklists/),
 * CC BY-SA 4.0, mirrored at github.com/olbat/ut1-blacklists. Hand-written rows
 * in dictionary.js win over anything here.
 *
 * ponytail: ${rows.length} rows parsed on every service-worker wake. Move it into
 * chrome.storage.local and look the suffix up key by key if it passes ~50k.
 */
export const GENERATED = {
${body},
};
`;
const target = fileURLToPath(new URL("../dictionary.generated.js", import.meta.url));
writeFileSync(target, file);
console.log(`\n${rows.length} rows -> ${target}`);
